if (missing.length) {
  console.error(`i18n: en missing keys: ${missing.join(', ')}`)
  // Fill gaps so runtime t() never hits undefined for typed keys.
  for (const k of missing) {
    ;(en as Record<string, string>)[k] = zhCN[k]
  }
}
