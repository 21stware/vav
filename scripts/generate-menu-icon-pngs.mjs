/**
 * Rasterize shared Lucide menu glyphs to PNG data URLs for the main process.
 * Run after editing `src/shared/menuLucideIcons.ts`.
 *
 *   node scripts/generate-menu-icon-pngs.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const iconsPath = join(root, 'src/shared/menuLucideIcons.ts')
const source = readFileSync(iconsPath, 'utf8')

const ICON_PX = 32

/** Parse `LUCIDE_MENU_ICON_NODES` object literal from the TS source. */
function parseIconNodes(text) {
  const start = text.indexOf('export const LUCIDE_MENU_ICON_NODES = {')
  if (start < 0) throw new Error('LUCIDE_MENU_ICON_NODES not found')
  let depth = 0
  let end = -1
  for (let i = text.indexOf('{', start); i < text.length; i++) {
    const ch = text[i]
    if (ch === '{') depth++
    else if (ch === '}') {
      depth--
      if (depth === 0) {
        end = i + 1
        break
      }
    }
  }
  if (end < 0) throw new Error('unterminated LUCIDE_MENU_ICON_NODES')
  // eslint-disable-next-line no-new-func
  return Function(`"use strict"; return (${text.slice(text.indexOf('{', start), end)})`)()
}

function escapeAttr(value) {
  return value.replace(/&/g, '&amp;').replace(/"/g, '&quot;')
}

function lucideSvgMarkup(nodes) {
  const body = nodes
    .map(([tag, attrs]) => {
      const attr = Object.entries(attrs)
        .map(([name, value]) => `${name}="${escapeAttr(value)}"`)
        .join(' ')
      return `<${tag} ${attr}/>`
    })
    .join('')
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${ICON_PX}" height="${ICON_PX}" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`
}

const iconNodes = parseIconNodes(source)
const entries = {}
for (const [key, nodes] of Object.entries(iconNodes)) {
  const svg = lucideSvgMarkup(nodes)
  const png = await sharp(Buffer.from(svg)).png().toBuffer()
  entries[key] = `data:image/png;base64,${png.toString('base64')}`
}

const out = join(root, 'src/shared/menuIconBitmaps.ts')
const body = `/** Generated by scripts/generate-menu-icon-pngs.mjs — do not edit by hand. */
import type { LucideMenuIconKey } from './menuLucideIcons'

export const MENU_ICON_BITMAPS: Record<LucideMenuIconKey, string> = ${JSON.stringify(entries, null, 2)} as const
`
writeFileSync(out, body)
console.log(`Wrote ${Object.keys(entries).length} icons → src/shared/menuIconBitmaps.ts`)
