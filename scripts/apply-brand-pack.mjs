/**
 * Bake `brand/<slug>/` into `src/shared/brand.generated.ts` and copy optional
 * icons onto the existing build / renderer paths.
 *
 *   BRAND=vav node scripts/apply-brand-pack.mjs
 *   BRAND=acme npm run brand:apply
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync, cpSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const slug = (process.env.BRAND || 'vav').trim() || 'vav'
const pack = join(root, 'brand', slug)

if (!existsSync(join(pack, 'identity.json'))) {
  throw new Error(`Brand pack missing identity.json: ${pack}`)
}

const identity = JSON.parse(readFileSync(join(pack, 'identity.json'), 'utf8'))
const promptPath = join(pack, 'prompts', 'system-identity.txt')
if (existsSync(promptPath)) {
  identity.systemIdentity = readFileSync(promptPath, 'utf8').trim()
}

function readOverlay(name) {
  const path = join(pack, 'i18n', name)
  if (!existsSync(path)) return {}
  const raw = JSON.parse(readFileSync(path, 'utf8'))
  return raw && typeof raw === 'object' ? raw : {}
}

const i18n = {
  en: readOverlay('en.json'),
  'zh-CN': readOverlay('zh-CN.json')
}

const brand = {
  slug: String(identity.slug || slug),
  displayName: String(identity.displayName || 'VAV'),
  displayNameDev: String(identity.displayNameDev || `${identity.displayName || 'VAV'} Dev`),
  appId: String(identity.appId || 'com.vav.app'),
  appIdDev: String(identity.appIdDev || 'dev.vav.app'),
  userDataDir: String(identity.userDataDir || 'vav'),
  userDataDirDev: String(identity.userDataDirDev || 'vav-dev'),
  copyright: String(identity.copyright || `Copyright © ${identity.displayName || 'VAV'}`),
  systemIdentity:
    String(identity.systemIdentity || '').trim() ||
    "You are {product}, a local coding agent running on the user's {os} machine."
}

const generated = `/** Generated by \`scripts/apply-brand-pack.mjs\`. Default pack: \`brand/${brand.slug}\`. */
import type { BrandIdentity, BrandI18nOverlays } from './brandIdentity.ts'

export const BRAND: BrandIdentity = ${JSON.stringify(brand, null, 2)}

export const BRAND_I18N: BrandI18nOverlays = ${JSON.stringify(i18n, null, 2)}
`

writeFileSync(join(root, 'src/shared/brand.generated.ts'), generated)
writeFileSync(join(root, 'build/brand-pack.json'), JSON.stringify(brand, null, 2) + '\n')

function copyIfPresent(from, to) {
  if (!existsSync(from)) return false
  mkdirSync(dirname(to), { recursive: true })
  cpSync(from, to)
  return true
}

const copies = [
  ['icon.png', 'build/icon.png'],
  ['icon-dark.png', 'build/icon-dark.png'],
  ['icon-mark.png', 'build/icon-mark.png'],
  ['wordmark.png', 'packages/vav-desktop/src/renderer/src/assets/wordmark.png'],
  ['wordmark-dark.png', 'packages/vav-desktop/src/renderer/src/assets/wordmark-dark.png']
]
for (const [name, dest] of copies) {
  if (copyIfPresent(join(pack, name), join(root, dest))) {
    console.log(`copied ${name} → ${dest}`)
  }
}

const composer = join(pack, 'icon-composer')
if (existsSync(composer)) {
  cpSync(composer, join(root, 'packages/vav-desktop/src/renderer/src/assets/icon'), {
    recursive: true
  })
  console.log('copied icon-composer → renderer assets/icon')
}

console.log(`brand pack ${brand.slug} (${brand.displayName})`)
